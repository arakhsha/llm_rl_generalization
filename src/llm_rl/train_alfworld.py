"""GRPO + LoRA training of an LLM agent on text-only ALFWorld.

Usage: python -m llm_rl.train_alfworld [hydra overrides], e.g. `experiment=alfworld_smoke`, or on several GPUs
`accelerate launch --num_processes N -m llm_rl.train_alfworld ...` (see scripts/train_alfworld.sbatch).

Episodes are generated by a custom rollout_func (llm_rl.alfworld_rollout) on TRL's colocated vLLM engine (one
per GPU), with the environments stepping in parallel worker processes. After training, the adapter and a merged
standalone model are saved to `keep_dir`.
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import hydra
import torch.distributed as dist
import wandb
from datasets import Dataset
from hydra.core.hydra_config import HydraConfig
from hydra.types import RunMode
from omegaconf import DictConfig, OmegaConf
from peft import LoraConfig
from transformers import TrainerCallback, set_seed
from transformers.trainer_utils import get_last_checkpoint
from trl import GRPOConfig, GRPOTrainer
from vllm import SamplingParams

from llm_rl.alfworld import AlfworldEnv, alfworld_reward, build_prompt, extract_games, load_manifest
from llm_rl.alfworld_rollout import EpisodeRunner, load_tokenizer, make_rollout_func, summarize
from llm_rl.env_pool import EnvPool


class AlfworldGRPOTrainer(GRPOTrainer):
    """Exposes the batch's dataset rows to the rollout function, which TRL only passes the prompts."""

    def _generate_and_score_completions(self, inputs):
        self.batch_inputs = inputs
        return super()._generate_and_score_completions(inputs)


class AlfworldEvalCallback(TrainerCallback):
    """Greedy success rate on the ALFWorld validation splits, run on the trainer's colocated vLLM engines.

    Each process plays a shard of the games; the main process writes and logs the merged results.
    """

    def __init__(self, runner: EpisodeRunner, splits: dict[str, list[dict]], every: int, out_dir: Path):
        self.runner = runner
        self.splits = splits
        self.every = every
        self.out_dir = out_dir
        self.trainer = None  # set once the trainer exists

    def on_step_end(self, args, state, control, **kwargs):
        if state.global_step % self.every == 0 or state.global_step == state.max_steps:
            self.evaluate(state.global_step)

    def evaluate(self, step: int) -> None:
        trainer, acc = self.trainer, self.trainer.accelerator
        # Push the current weights to vLLM, as GRPOTrainer does before generating.
        if trainer._last_loaded_step != step:
            trainer.vllm_generation.sync_weights()
            trainer._last_loaded_step = step
        metrics = {}
        for split, rows in self.splits.items():
            shard = rows[acc.process_index :: acc.num_processes]
            episodes = self.runner.run(trainer.vllm_generation.llm, shard, SamplingParams(temperature=0.0))
            records = [self.runner.record(ep) for ep in episodes]
            if acc.num_processes > 1:
                gathered = [None] * acc.num_processes
                dist.all_gather_object(gathered, records)
                records = [r for shard_records in gathered for r in shard_records]
            metrics.update({f"eval/{split}/{k}": v for k, v in summarize(records).items()})
            if acc.is_main_process:
                with open(self.out_dir / f"step_{step}_{split}.jsonl", "w") as f:
                    f.writelines(json.dumps(r) + "\n" for r in records)
        if acc.is_main_process:
            with open(self.out_dir / "history.jsonl", "a") as f:
                f.write(json.dumps({"step": step, **metrics}) + "\n")
            success = {k: round(v, 4) for k, v in metrics.items() if k.endswith("/success")}
            print(f"[eval step {step}] {success}")
            if wandb.run is not None:
                wandb.log({**metrics, "train/global_step": step})


@hydra.main(version_base="1.3", config_path="../../configs", config_name="train_alfworld")
def main(cfg: DictConfig) -> None:
    hydra_cfg = HydraConfig.get()
    run_dir = Path(hydra_cfg.runtime.output_dir)
    run_id = cfg.run_name if hydra_cfg.mode == RunMode.RUN else f"{cfg.run_name}-{hydra_cfg.job.num}"
    # Set by accelerate launch; all processes share run_dir, so run_name must not depend on launch time.
    is_main = int(os.environ.get("RANK", 0)) == 0
    world_size = int(os.environ.get("WORLD_SIZE", 1))
    set_seed(cfg.seed)

    # First, while the process is still single-threaded: the pool forks its workers.
    games_dir = extract_games(cfg.env.data_dir, cfg.env.games_dir)
    pool = EnvPool(
        AlfworldEnv,
        cfg.env.num_workers,
        games_dir=games_dir,
        max_steps=cfg.env.max_steps,
        admissible_commands=cfg.env.admissible_commands,
    )

    if cfg.wandb.enabled and is_main:
        # Started here so the run carries the full Hydra config; TRL's callback reuses the active run.
        wandb.init(
            project=cfg.wandb.project,
            entity=cfg.wandb.entity,
            name=run_id,
            id=run_id,
            resume="allow",
            tags=list(cfg.wandb.tags),
            config=OmegaConf.to_container(cfg, resolve=True),
        )

    tokenizer, chat_template = load_tokenizer(cfg.model.name_or_path)
    runner = EpisodeRunner(
        tokenizer,
        chat_template,
        pool,
        max_steps=cfg.env.max_steps,
        max_completion_length=cfg.env.max_completion_length,
        enable_thinking=cfg.model.enable_thinking,
    )

    # The prompt column is only used for logging; the rollout function renders each game's own prompt.
    prompt = build_prompt()
    train_ds = Dataset.from_list([{"prompt": prompt, **row} for row in load_manifest(cfg.env.data_dir, "train")])

    eval_dir = run_dir / "eval"
    eval_dir.mkdir(parents=True, exist_ok=True)
    eval_splits = {s: load_manifest(cfg.env.data_dir, s)[: cfg.eval.limit or None] for s in cfg.eval.splits}
    eval_callback = AlfworldEvalCallback(runner, eval_splits, cfg.eval.steps, eval_dir)

    # Keep episodes per optimizer step fixed whatever the number of GPUs.
    trainer_cfg = OmegaConf.to_container(cfg.trainer, resolve=True)
    per_step = trainer_cfg["per_device_train_batch_size"] * world_size
    assert cfg.episodes_per_step % per_step == 0, (cfg.episodes_per_step, per_step)
    args = GRPOConfig(
        **trainer_cfg,
        gradient_accumulation_steps=cfg.episodes_per_step // per_step,
        output_dir=str(run_dir),
        run_name=run_id,
        seed=cfg.seed,
        report_to="wandb" if cfg.wandb.enabled else "none",
    )
    trainer = AlfworldGRPOTrainer(
        model=cfg.model.name_or_path,
        reward_funcs=[alfworld_reward],
        args=args,
        train_dataset=train_ds,
        peft_config=LoraConfig(**OmegaConf.to_container(cfg.lora, resolve=True)),
        rollout_func=make_rollout_func(runner),
        callbacks=[eval_callback],
    )
    eval_callback.trainer = trainer
    if is_main:
        trainer.model.print_trainable_parameters()

    checkpoint = get_last_checkpoint(str(run_dir)) if cfg.resume else None
    if checkpoint:
        print(f"Resuming from {checkpoint}")
    trainer.train(resume_from_checkpoint=checkpoint)
    adapter_dir = run_dir / "final_adapter"
    trainer.save_model(str(adapter_dir))
    pool.close()
    trainer.vllm_generation.llm.llm_engine.engine_core.shutdown()
    if not is_main:
        return

    # Keep the adapter, a merged standalone model, the config and the validation history.
    keep_dir = Path(cfg.keep_dir)
    keep_dir.mkdir(parents=True, exist_ok=True)
    shutil.copytree(adapter_dir, keep_dir / "adapter", dirs_exist_ok=True)
    # In a fresh interpreter: vLLM has swapped in its own Qwen3.5 config classes in this one.
    subprocess.run([sys.executable, "-m", "llm_rl.merge", str(adapter_dir), str(keep_dir / "merged")], check=True)
    OmegaConf.save(cfg, keep_dir / "config.yaml", resolve=True)
    shutil.copy(eval_dir / "history.jsonl", keep_dir / "eval_history.jsonl")
    print(f"Saved adapter and merged model to {keep_dir}")

    if cfg.wandb.enabled:
        wandb.summary["keep_dir"] = str(keep_dir)
        wandb.finish()


if __name__ == "__main__":
    main()
